"""Transcode only the project's original synthetic fixtures, never real evidence."""
from pathlib import Path
import subprocess
out=Path('public/samples/media');out.mkdir(parents=True,exist_ok=True)
audio=Path('public/samples/audio/tones.wav');video=Path('public/samples/video/demo.mp4')
if not video.exists():
 choices=list(Path('public/samples/video').glob('*.mp4'))
 if not choices:raise RuntimeError('Original video fixture missing')
 video=choices[0]
for ext,codec in [('mp3','libmp3lame'),('flac','flac'),('m4a','aac'),('ogg','libvorbis')]:
 subprocess.run(['ffmpeg','-y','-hide_banner','-loglevel','error','-i',str(audio),'-metadata','title=Original DGC synthetic tone','-c:a',codec,str(out/('tones.'+ext))],check=True)
for ext,codec in [('avi','mpeg4'),('mkv','ffv1'),('mov','mpeg4'),('webm','libvpx')]:
 subprocess.run(['ffmpeg','-y','-hide_banner','-loglevel','error','-i',str(video),'-an','-metadata','title=Original DGC synthetic clip','-c:v',codec,str(out/('clip.'+ext))],check=True)
(out/'README.md').write_text('# Original media metadata examples\n\nGenerated by scripts/generate-media-samples.py with local FFmpeg from original project tone and video fixtures. No captured personal media. MP3/FLAC/M4A/OGG and AVI/MKV/MOV/WebM exercise container/codec metadata parsing; titles deliberately identify synthetic examples. Encoding fields are not origin proof.\n')
