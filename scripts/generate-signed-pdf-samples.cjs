/* Original synthetic PDF signatures and preserved-revision fixtures. Temporary keys deleted. */
const fs = require('fs'),
  os = require('os'),
  path = require('path'),
  cp = require('child_process');
const P = require('pdf-lib');
const E = require('../public/pdf-evidence');
const out = path.resolve('public/samples/document/signatures');
fs.mkdirSync(out, { recursive: true });
const run = (args) => cp.execFileSync('openssl', args, { stdio: ['ignore', 'ignore', 'pipe'] });
function increment(base, title) {
  const chain = E.revisionChain(new Uint8Array(base), P),
    prev = chain.at(-1).offset;
  const text = base.toString('latin1');
  const size = Number([...text.matchAll(/\/Size\s+(\d+)/g)].at(-1)[1]);
  const root = [...text.matchAll(/\/Root\s+(\d+\s+\d+\s+R)/g)].at(-1)[1];
  const object = Buffer.from(
    `\n${size} 0 obj\n<< /Title (${title}) /Author (Synthetic claimed editor) /ModDate (D:20261112020000Z) >>\nendobj\n`,
  );
  const offset = base.length + 1,
    xref = base.length + object.length;
  const tail = Buffer.from(
    `xref\n${size} 1\n${String(offset).padStart(10, '0')} 00000 n \ntrailer\n<< /Size ${size + 1} /Root ${root} /Info ${size} 0 R /Prev ${prev} >>\nstartxref\n${xref}\n%%EOF\n`,
  );
  return Buffer.concat([base, object, tail]);
}
(async () => {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'dgc-synthetic-sign-'));
  try {
    run([
      'req',
      '-x509',
      '-newkey',
      'rsa:2048',
      '-nodes',
      '-keyout',
      dir + '/key.pem',
      '-out',
      dir + '/cert.pem',
      '-days',
      '365',
      '-subj',
      '/CN=DGC Synthetic Signature Fixture/O=Original Test Data',
    ]);
    const doc = await P.PDFDocument.create();
    const page = doc.addPage([400, 300]);
    page.drawText('DGC ORIGINAL SIGNED TEST - NOT EVIDENCE', { x: 25, y: 250, size: 12 });
    doc.setTitle('Initial signed revision');
    const signature = doc.context.obj({
      Type: 'Sig',
      Filter: 'Adobe.PPKLite',
      SubFilter: 'adbe.pkcs7.detached',
      ByteRange: [0, 1111111111, 2222222222, 3333333333],
      Contents: P.PDFHexString.of('0'.repeat(16384)),
      Reason: P.PDFString.of('Original synthetic test'),
    });
    const sigRef = doc.context.register(signature),
      field = doc.context.obj({
        Type: 'Annot',
        Subtype: 'Widget',
        FT: 'Sig',
        T: P.PDFString.of('SyntheticSignature'),
        V: sigRef,
        Rect: [0, 0, 0, 0],
        P: page.ref,
      });
    const fieldRef = doc.context.register(field);
    doc.catalog.set(P.PDFName.of('AcroForm'), doc.context.obj({ Fields: [fieldRef], SigFlags: 3 }));
    page.node.set(P.PDFName.of('Annots'), doc.context.obj([fieldRef]));
    let bytes = Buffer.from(await doc.save({ useObjectStreams: false })),
      text = bytes.toString('latin1');
    const contents = text.match(/\/Contents\s*(<0{16384}>)/),
      start = contents.index + contents[0].indexOf('<'),
      end = start + contents[1].length;
    const range = text.match(/\[ 0 1111111111 2222222222 3333333333 \]/);
    if (!range) throw Error('ByteRange placeholder missing.');
    const patched = `[0 ${start} ${end} ${bytes.length - end}]`.padEnd(range[0].length, ' ');
    bytes.write(patched, range.index, 'ascii');
    const signedData = Buffer.concat([bytes.subarray(0, start), bytes.subarray(end)]);
    fs.writeFileSync(dir + '/data.bin', signedData);
    run([
      'cms',
      '-sign',
      '-binary',
      '-md',
      'sha256',
      '-in',
      dir + '/data.bin',
      '-signer',
      dir + '/cert.pem',
      '-inkey',
      dir + '/key.pem',
      '-outform',
      'DER',
      '-out',
      dir + '/sig.der',
      '-nosmimecap',
    ]);
    const cms = fs.readFileSync(dir + '/sig.der');
    if (cms.length > 8192) throw Error('CMS fixture exceeds reserved gap.');
    bytes.write(cms.toString('hex').padEnd(16384, '0'), start + 1, 'ascii');
    fs.writeFileSync(out + '/valid.pdf', bytes);
    const tampered = Buffer.from(bytes),
      titleOffset = tampered.indexOf(Buffer.from('/Reason (Original synthetic test)')) + 10;
    if (titleOffset < 10) throw Error('Title missing');
    tampered[titleOffset] ^= 1;
    fs.writeFileSync(out + '/tampered.pdf', tampered);
    const later = increment(bytes, 'Later appended unsigned revision');
    fs.writeFileSync(out + '/later-update.pdf', later);
    fs.writeFileSync(out + '/two-updates.pdf', increment(later, 'Third preserved revision'));
    fs.writeFileSync(out + '/signer-public.pem', fs.readFileSync(dir + '/cert.pem'));
    fs.writeFileSync(
      out + '/README.md',
      '# Original detached signature fixtures\n\nGenerated by scripts/generate-signed-pdf-samples.cjs using pdf-lib and OpenSSL CMS with an ephemeral synthetic key deleted after generation. The public self-signed certificate is not trusted. valid.pdf has a real SHA-256/RSA detached CMS signature; tampered.pdf changes signed title bytes; later-update.pdf preserves the valid old signature but adds an unsigned metadata revision; two-updates.pdf contains three linked preserved revisions. No real evidence or production keys.\n',
    );
    console.log(
      'Created signed/tampered/appended PDF fixtures; ephemeral private key deleted at exit.',
    );
  } finally {
    fs.rmSync(dir, { recursive: true, force: true });
  }
})().catch((e) => {
  console.error(e);
  process.exitCode = 1;
});
