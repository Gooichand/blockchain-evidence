from pathlib import Path
from PIL import Image,ImageDraw,ImageFilter
import numpy as np,json,hashlib
root=Path(__file__).resolve().parents[1]/'public/samples/images/copy-move'
root.mkdir(parents=True,exist_ok=True)
rng=np.random.default_rng(314159)
# Original multi-scale noise and independent shapes, no repeated template.
a=rng.integers(20,235,(480,640,3),dtype=np.uint8)
im=Image.fromarray(a).filter(ImageFilter.GaussianBlur(1.2));draw=ImageDraw.Draw(im)
for i in range(180):
 x,y=map(int,[rng.integers(5,620),rng.integers(5,460)]);r=int(rng.integers(3,15));color=tuple(map(int,rng.integers(10,245,3)))
 if i%2:draw.ellipse((x,y,x+r,y+r),outline=color,width=2)
 else:draw.line((x,y,x+r*2,y+r),fill=color,width=2)
im.save(root/'unique.png');patch=im.crop((60,55,220,205))
clone=im.copy();clone.paste(patch,(355,265));clone.save(root/'translated.png');clone.save(root/'recompressed.jpg',quality=80)
changed=patch.resize((184,173),Image.Resampling.BICUBIC).rotate(18,Image.Resampling.BICUBIC,expand=True,fillcolor=(120,120,120))
transformed=im.copy();transformed.paste(changed,(340,220));transformed.save(root/'rotated-scaled.jpg',quality=88)
Image.new('RGB',(640,480),(90,90,90)).save(root/'flat.png')
manifest={'source':'Original deterministic textured images, synthetic validation only. Not a natural-image accuracy benchmark.','sourceRegion':[60,55,220,205],'translationPaste':[355,265],'rotatedScaled':{'scale':1.15,'degrees':18,'paste':[340,220]},'sha256':{p.name:hashlib.sha256(p.read_bytes()).hexdigest() for p in root.iterdir() if p.suffix in ['.png','.jpg']}}
(root/'manifest.json').write_text(json.dumps(manifest,indent=2)+'\n')
(root/'README.md').write_text('Original synthetic fixtures generated by scripts/generate-copy-move-samples.py. Apache-2.0 with this repository. Unique and flat negatives; off-grid translation, JPEG recompression, rotation/scale positives. Natural repetition can create valid feature correspondences without editing; no authenticity claim.\n')
