"""Generate original, non-routable example traffic. Never captures or sends packets."""
import struct, socket, json
from pathlib import Path
OUT=Path(__file__).resolve().parents[1]/'public/samples/network'
OUT.mkdir(parents=True,exist_ok=True)
def checksum(b):
 if len(b)%2:b+=b'\0'
 s=sum(struct.unpack('!%dH'%(len(b)//2),b))
 while s>>16:s=(s&65535)+(s>>16)
 return (~s)&65535
def ipv4(src,dst,proto,data,ident=1):
 a,b=socket.inet_aton(src),socket.inet_aton(dst)
 head=struct.pack('!BBHHHBBH4s4s',0x45,0,20+len(data),ident,0,64,proto,0,a,b)
 head=head[:10]+struct.pack('!H',checksum(head))+head[12:]
 return head+data
def tcp(src,dst,sp,dp,seq,ack,flags,payload=b''):
 h=struct.pack('!HHIIBBHHH',sp,dp,seq,ack,0x50,flags,65535,0,0)+payload
 pseudo=socket.inet_aton(src)+socket.inet_aton(dst)+struct.pack('!BBH',0,6,len(h))
 return h[:16]+struct.pack('!H',checksum(pseudo+h))+h[18:]
def ethernet(payload,reverse=False):
 a,b=bytes.fromhex('020000000001'),bytes.fromhex('020000000002')
 return (a+b if reverse else b+a)+b'\x08\x00'+payload
question=b'\x04demo\x07example\x00'+struct.pack('!HH',1,1)
dns=struct.pack('!6H',0x1234,0x0100,1,0,0,0)+question
udp=struct.pack('!HHHH',53000,53,8+len(dns),0)+dns
packets=[ethernet(ipv4('192.0.2.10','192.0.2.53',17,udp)),ethernet(ipv4('192.0.2.10','198.51.100.20',6,tcp('192.0.2.10','198.51.100.20',50000,80,1,0,2))),ethernet(ipv4('198.51.100.20','192.0.2.10',6,tcp('198.51.100.20','192.0.2.10',80,50000,100,2,18)),True),ethernet(ipv4('192.0.2.10','198.51.100.20',6,tcp('192.0.2.10','198.51.100.20',50000,80,2,101,24,b'GET /demo HTTP/1.1\r\nHost: demo.example\r\n\r\n'))) ]
epoch=1794412800
pcap=struct.pack('<IHHIIII',0xa1b2c3d4,2,4,0,0,65535,1)
for i,b in enumerate(packets):pcap+=struct.pack('<IIII',epoch+i,0,len(b),len(b))+b
(OUT/'demo.pcap').write_bytes(pcap)
def block(t,data):
 data+=b'\0'*((-len(data))%4);size=12+len(data)
 return struct.pack('<II',t,size)+data+struct.pack('<I',size)
ng=block(0x0a0d0d0a,struct.pack('<IHHq',0x1a2b3c4d,1,0,-1))+block(1,struct.pack('<HHI',1,0,65535))
for i,b in enumerate(packets):
 ticks=(epoch+i)*1000000
 ng+=block(6,struct.pack('<IIIII',0,ticks>>32,ticks&0xffffffff,len(b),len(b))+b)
(OUT/'demo.pcapng').write_bytes(ng)
(OUT/'expected.json').write_text(json.dumps({'originalSynthetic':True,'neverCapturedOrSent':True,'packetCount':4,'flowCount':2,'dnsQuestion':'demo.example','httpFirstLine':'GET /demo HTTP/1.1','tcpPackets':3,'udpPackets':1},indent=2)+'\n')
(OUT/'README.md').write_text('# Original offline packet examples\n\nGenerated by scripts/generate-network-samples.py. Four synthetic Ethernet/IPv4 packets: DNS query, TCP SYN/SYNACK and HTTP request. Documentation-address ranges and demo.example are used. No packets were captured from a real person or sent to any host. Classic PCAP and PCAPNG encode the same packets. Checksums: IPv4/TCP computed, IPv4 UDP zero checksum is intentional.\n')
