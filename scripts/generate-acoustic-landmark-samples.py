#!/usr/bin/env python3
"""Original synthetic acoustic landmark fixtures. No external recordings."""
import math, struct, wave, subprocess, json, hashlib
from pathlib import Path
root=Path(__file__).resolve().parents[1]/'public/samples/audio/landmarks'
root.mkdir(parents=True,exist_ok=True)
def signal(seed,rate=16000):
 state=seed
 def rand():
  nonlocal state
  state=(state*1664525+1013904223)&0xffffffff
  return state/4294967296
 out=[]
 for n in range(40):
  f=180+int(rand()*1800);g=200+int(rand()*1600);a=rand()*6;b=rand()*6
  for j in range(int(rate*.3)):
   t=j/rate;e=math.sin(math.pi*j/(rate*.3))**2
   x=.3*e*(math.sin(2*math.pi*f*t+a)+.6*math.sin(2*math.pi*g*t+b)+.3*math.sin(2*math.pi*f*2*t))+.006*(rand()-.5)
   out.append(max(-32768,min(32767,round(x*32767))))
 return out
def wav(name,samples,rate=16000):
 with wave.open(str(root/name),'wb') as f:
  f.setnchannels(1);f.setsampwidth(2);f.setframerate(rate);f.writeframes(struct.pack('<'+'h'*len(samples),*samples))
a=signal(123);wav('original.wav',a);wav('different.wav',signal(321))
# Same spectral segments in a different time order: no original aligned two-second passage.
blocks=[a[i:i+4800] for i in range(0,len(a),4800)]
wav('reordered.wav',sum([blocks[(i*17+11)%40] for i in range(40)],[]))
for name,filters,codec,extra in [
 ('trimmed.mp3','atrim=start=0.734,asetpts=PTS-STARTPTS,volume=0.35','libmp3lame',['-b:a','96k']),
 ('resampled.m4a','aresample=44100','aac',['-b:a','96k']),
 ('noisy.wav','volume=0.5,anoisesrc=d=12:a=0.005:seed=17[n];[0:a][n]amix=inputs=2:normalize=0','pcm_s16le',[])]:
 cmd=['ffmpeg','-y','-hide_banner','-loglevel','error','-i',str(root/'original.wav')]
 if name=='noisy.wav':
  cmd+=['-filter_complex','[0:a]volume=0.5[a];anoisesrc=d=12:a=0.005:seed=17[n];[a][n]amix=inputs=2:normalize=0']
 else:cmd+=['-af',filters]
 subprocess.run(cmd+['-c:a',codec]+extra+[str(root/name)],check=True)
manifest={'originalSource':'Deterministic original synthetic multi-tone envelopes. Not a natural-recording accuracy benchmark.','seed':123,'rate':16000,'seconds':12,'trimmedOffsetSeconds':-0.734,'files':{p.name:hashlib.sha256(p.read_bytes()).hexdigest() for p in root.iterdir() if p.is_file() and p.suffix not in ['.json','.md']}}
(root/'manifest.json').write_text(json.dumps(manifest,indent=2)+'\n')
(root/'README.md').write_text('Original synthetic audio, generated by scripts/generate-acoustic-landmark-samples.py. May be used with this repository under Apache-2.0. Positives: identical, gain/noise, MP3 trim and AAC resample. Negatives: different seed and reordered segments. These fixtures do not establish broad recording-identification accuracy. FFmpeg transform details are in the generator.\n')
